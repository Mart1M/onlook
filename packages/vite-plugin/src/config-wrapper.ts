import { ONLOOK_CACHE_DIRECTORY, ONLOOK_DEV_PRELOAD_SCRIPT_SRC } from '@onlook/constants';

/** Relative path written into the project tooling dir (not user source). */
export const ONLOOK_VITE_CONFIG_PATH = `${ONLOOK_CACHE_DIRECTORY}/vite.config.mjs`;

const USER_CONFIG_CANDIDATES = [
    'vite.config.ts',
    'vite.config.mts',
    'vite.config.js',
    'vite.config.mjs',
    'vite.config.cts',
    'vite.config.cjs',
] as const;

/**
 * Self-contained Vite config that merges the user's config (if any) and adds
 * the Onlook preload plugin inline — so the project does not need
 * `@onlook/vite-plugin` installed in its own node_modules.
 */
export function buildOnlookViteConfigSource(options?: {
    scriptSrc?: string;
    userConfigCandidates?: readonly string[];
}): string {
    const scriptSrc = options?.scriptSrc ?? ONLOOK_DEV_PRELOAD_SCRIPT_SRC;
    const candidates = options?.userConfigCandidates ?? USER_CONFIG_CANDIDATES;
    const candidatesLiteral = JSON.stringify([...candidates]);

    return `/**
 * Generated by Onlook (SID-26). Do not edit by hand.
 * Injects the preload bridge via transformIndexHtml without rewriting user layout/index.html.
 */
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { defineConfig, mergeConfig, loadConfigFromFile } = require('vite');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCRIPT_SRC = ${JSON.stringify(scriptSrc)};
const USER_CONFIG_CANDIDATES = ${candidatesLiteral};

function onlookPreloadPlugin() {
  const SCRIPT_ID = 'onlook-preload-script';
  const tag = '<script type="module" src="' + SCRIPT_SRC + '" id="' + SCRIPT_ID + '"></script>';
  return {
    name: 'onlook-preload',
    enforce: 'pre',
    transformIndexHtml(html) {
      if (html.includes(SCRIPT_ID)) return html;
      if (/<\\/body>/i.test(html)) {
        return html.replace(/<\\/body>/i, '  ' + tag + '\\n</body>');
      }
      if (/<\\/html>/i.test(html)) {
        return html.replace(/<\\/html>/i, '  ' + tag + '\\n</html>');
      }
      return html + '\\n' + tag + '\\n';
    },
  };
}

async function loadUserConfig(env) {
  for (const name of USER_CONFIG_CANDIDATES) {
    const configFile = path.join(root, name);
    try {
      const loaded = await loadConfigFromFile(env, configFile);
      if (loaded?.config) {
        return loaded.config;
      }
    } catch {
      // try next candidate
    }
  }
  return {};
}

export default defineConfig(async (env) => {
  const user = await loadUserConfig(env);
  return mergeConfig(user, {
    root,
    plugins: [onlookPreloadPlugin()],
  });
});
`;
}

export function viteDevCommandWithOnlookConfig(packageManagerRunPrefix: string): string {
    // e.g. `bunx vite --config .onlook/vite.config.mjs`
    const runner =
        packageManagerRunPrefix === 'bun run'
            ? 'bunx'
            : packageManagerRunPrefix === 'pnpm run'
              ? 'pnpm exec'
              : packageManagerRunPrefix === 'yarn'
                ? 'yarn'
                : 'npx';
    if (runner === 'yarn') {
        return `yarn vite --config ${ONLOOK_VITE_CONFIG_PATH}`;
    }
    return `${runner} vite --config ${ONLOOK_VITE_CONFIG_PATH}`;
}
